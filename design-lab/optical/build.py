def cross(a,b,c):
    return (b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0])

def triangulate(poly):
    ids=list(range(len(poly))); result=[]
    while len(ids)>3:
        for k,b in enumerate(ids):
            a,c=ids[k-1],ids[(k+1)%len(ids)]
            if cross(poly[a],poly[b],poly[c])<=1e-5: continue
            if any(all(cross(poly[x],poly[y],poly[p])>=-1e-5 for x,y in [(a,b),(b,c),(c,a)]) for p in ids if p not in (a,b,c)): continue
            result.append([poly[a],poly[b],poly[c]]);ids.pop(k);break
        else: raise ValueError('Cannot triangulate')
    result.append([poly[i] for i in ids]);return result

def inset(poly,amount):
    result=[]
    for i,b in enumerate(poly):
        a,c=poly[i-1],poly[(i+1)%len(poly)]
        u=[b[0]-a[0],b[1]-a[1]];v=[c[0]-b[0],c[1]-b[1]]
        lu,lv=math.hypot(*u),math.hypot(*v)
        u=[x/lu for x in u];v=[x/lv for x in v]
        n=[-u[1]-v[1],u[0]+v[0]];den=1+u[0]*v[0]+u[1]*v[1]
        result.append([b[0]+amount*n[0]/den,b[1]+amount*n[1]/den])
    return result

faces=[];x=46;outlines=[]
for letter,poly in enumerate(LETTERS):
    poly=[[a+x,b+65] for a,b in poly];outlines.append(poly)
    inner=inset(poly,9)
    for i,a in enumerate(poly):
        j=(i+1)%len(poly);b=poly[j];dx,dy=b[0]-a[0],b[1]-a[1];l=math.hypot(dx,dy)
        normal=[dy/l*.78,-dx/l*.78,.625]
        for tri in [[a,b,inner[j]],[a,inner[j],inner[i]]]:faces.append(dict(p=tri,n=normal,edge=1,letter=letter))
    for i,tri in enumerate(triangulate(inner)):
        # Each crown triangle is divided at its centroid into three optical cuts.
        center=[sum(p[k] for p in tri)/3 for k in (0,1)]
        for j in range(3):
            angle=(i*2.399+j*2.094+letter*.7)
            tilt=.22+.22*((i+j)%3)/2
            faces.append(dict(p=[tri[j],tri[(j+1)%3],center],n=[math.cos(angle)*tilt,math.sin(angle)*tilt,math.sqrt(1-tilt*tilt)],edge=0,letter=letter))
    x+=max(p[0] for p in LETTERS[letter])+28
